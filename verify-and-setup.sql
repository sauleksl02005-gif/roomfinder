-- Les tables chambres et messages ont déjà été créées ?
-- Exécutez ce script dans Supabase SQL Editor pour compléter les colonnes/bucket manquants.

create table if not exists public.chambres (
  id text primary key,
  titre text not null,
  ville text not null,
  quartier text,
  prix numeric not null,
  duree text not null,
  description text,
  adresse text,
  latitude double precision,
  longitude double precision,
  telephone text,
  equipements text,
  photos text[] not null default '{}',
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.chambres add column if not exists published boolean not null default true;
alter table public.chambres add column if not exists photos text[] not null default '{}';

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id text not null,
  room_title text not null,
  name text not null,
  phone text not null,
  message text not null,
  created_at timestamptz not null default now()
);

insert into storage.buckets (id, name, public)
values ('room-photos', 'room-photos', true)
on conflict (id) do update set public = excluded.public;

-- Autoriser l'affichage public des images du bucket. Les téléversements sont faits
-- par le serveur avec SUPABASE_SERVICE_ROLE_KEY, qui ne doit jamais être exposée au navigateur.
drop policy if exists "RoomFinder public photo read" on storage.objects;
create policy "RoomFinder public photo read"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'room-photos');
