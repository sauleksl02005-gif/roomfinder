-- À exécuter dans Supabase SQL Editor après vérification des tables existantes.
create table if not exists public.chambres (
  id text primary key,
  titre text not null,
  ville text not null,
  quartier text default '',
  prix numeric not null,
  duree text not null,
  description text default '',
  adresse text default '',
  latitude double precision,
  longitude double precision,
  telephone text default '',
  equipements text default '',
  photos text[] not null default '{}',
  published boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id text,
  room_title text,
  name text not null,
  phone text not null,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.chambres add column if not exists photos text[] not null default '{}';
alter table public.chambres add column if not exists published boolean not null default true;
insert into storage.buckets (id, name, public) values ('room-photos', 'room-photos', true) on conflict (id) do update set public = true;
create policy "RoomFinder public read room photos" on storage.objects for select to public using (bucket_id = 'room-photos');
